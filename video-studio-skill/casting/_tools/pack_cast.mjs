// Packs the picked cast (recoloured pose SVGs) into assets/cast.js for the composition.
import fs from "node:fs";
import path from "node:path";
const SRC = path.resolve(process.argv[2]);
const OUT = path.resolve(process.argv[3]);
const roles = { strategist: "op-strategist", agentA: "op-agent-a", agentB: "op-agent-b", agentC: "op-agent-c", client: "op-client", planner: "op-planner", cfo: "op-cfo", accountant: "op-accountant", engineer: "op-engineer" };
const cast = {};
for (const [role, id] of Object.entries(roles)) {
  const dir = fs.existsSync(path.join(SRC, id, "recoloured")) ? path.join(SRC, id, "recoloured") : path.join(SRC, id);
  cast[role] = fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort().map((f) => {
    const s = fs.readFileSync(path.join(dir, f), "utf8");
    const inner = s.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    return { name: f.replace(/^\d+-|\.svg$/g, ""), sitting: /sitting\//.test(s), svg: inner };
  });
}
fs.writeFileSync(OUT, "// Generated by tools/pack_cast.mjs from research/casting (Open Peeps, CC0). Do not edit by hand.\nwindow.CAST = " + JSON.stringify(cast) + ";\n");
console.log(Object.entries(cast).map(([k, v]) => k + ":" + v.map((p) => p.name).join(",")).join("\n"));
